"""
Models for the History application.

Stores persistent query logs, answers, citations, abstention status,
and tamper-resistant AgentOps provenance records for engineer self-auditing
and supervisor monitoring.
"""

import uuid
from django.conf import settings
from django.db import models
from django.utils.translation import gettext_lazy as _

from documents.models import Document
from machines.models import Machine


class EvidenceGateOutcome(models.TextChoices):
    PASS = 'PASS', _('Evidence Pass')
    PARTIAL = 'PARTIAL', _('Evidence Partial')
    FAIL = 'FAIL', _('Evidence Fail')


class EscalationStatus(models.TextChoices):
    NONE = 'NONE', _('None')
    PENDING = 'PENDING', _('Pending Supervisor Review')
    RESOLVED = 'RESOLVED', _('Resolved')
    REJECTED = 'REJECTED', _('Rejected')


class QueryRecord(models.Model):
    """
    Persistent log of questions posed to machines, generated RAG answers,
    and supporting document citations.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
        help_text=_('Unique query record UUID identifier.')
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='query_records',
        verbose_name=_('user'),
        help_text=_('Engineer or user who executed the query.')
    )
    machine = models.ForeignKey(
        'machines.Machine',
        on_delete=models.CASCADE,
        related_name='query_records',
        verbose_name=_('machine'),
        help_text=_('Target machine queried.')
    )
    question = models.TextField(
        _('question'),
        help_text=_('Natural language query submitted by user.')
    )
    answer = models.TextField(
        _('answer'),
        help_text=_('Grounded response generated by the RAG pipeline.')
    )
    abstained = models.BooleanField(
        _('abstained'),
        default=False,
        help_text=_('True if system abstained due to insufficient context.')
    )
    citations = models.JSONField(
        _('citations'),
        default=list,
        blank=True,
        help_text=_('Structured citation references pointing to document pages.')
    )
    evidence_status = models.CharField(
        _('evidence status'),
        max_length=20,
        choices=EvidenceGateOutcome.choices,
        default=EvidenceGateOutcome.PASS,
        db_index=True,
        help_text=_('Evidence sufficiency evaluation: PASS, PARTIAL, or FAIL.')
    )
    intent = models.CharField(
        _('classified intent'),
        max_length=50,
        default='troubleshooting',
        blank=True,
        help_text=_('Intent classification: troubleshooting, maintenance, safety, general.')
    )
    fault_code = models.CharField(
        _('fault code'),
        max_length=100,
        blank=True,
        help_text=_('Extracted fault or error code.')
    )
    trace_id = models.CharField(
        _('OpenTelemetry trace ID'),
        max_length=64,
        blank=True,
        db_index=True,
        help_text=_('Distributed trace ID.')
    )
    duration_ms = models.PositiveIntegerField(
        _('processing duration (ms)'),
        default=0,
        help_text=_('Total end-to-end execution latency in milliseconds.')
    )
    created_at = models.DateTimeField(
        _('created at'),
        auto_now_add=True,
        db_index=True,
        help_text=_('Timestamp of when the query was executed.')
    )

    class Meta:
        db_table = 'query_records'
        verbose_name = _('query record')
        verbose_name_plural = _('query records')
        ordering = ['-created_at']

    def __str__(self):
        return f"Query {self.id} by {self.user.email} on {self.machine.machine_code} at {self.created_at}"

    @property
    def is_insufficient_evidence(self):
        return self.abstained

    @property
    def engineer_name(self):
        if self.user:
            return f"{self.user.first_name} {self.user.last_name}".strip() or self.user.email
        return "Plant Engineer"


# Alias QuestionRecord to QueryRecord for compatibility with ZIP scripts
QuestionRecord = QueryRecord


class Citation(models.Model):
    """
    Normalized relational record for an individual factual claim citation.
    Guarantees document existence, revision traceability, and PDF page grounding.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )
    query = models.ForeignKey(
        QueryRecord,
        on_delete=models.CASCADE,
        related_name='citation_records',
        verbose_name=_('query record')
    )
    document = models.ForeignKey(
        Document,
        on_delete=models.CASCADE,
        related_name='cited_instances',
        verbose_name=_('source document')
    )
    document_title = models.CharField(_('document title'), max_length=255)
    revision = models.CharField(_('document revision'), max_length=50, default='1.0')
    page_number = models.PositiveIntegerField(_('page number'))
    chunk_id = models.CharField(_('chunk ID'), max_length=128, blank=True)
    source_text = models.TextField(_('supporting passage text'), blank=True)
    similarity_score = models.FloatField(_('relevance score'), default=0.0)
    retrieval_method = models.CharField(
        _('retrieval method'),
        max_length=50,
        default='vector',
        help_text=_('Method used: vector, bm25, or hybrid_rrf.')
    )
    is_verified = models.BooleanField(
        _('citation verified'),
        default=True,
        help_text=_('Whether claim-to-source page validation passed.')
    )
    verification_notes = models.TextField(_('verification notes'), blank=True)
    created_at = models.DateTimeField(_('created at'), auto_now_add=True)

    class Meta:
        db_table = 'assistant_citations'
        verbose_name = _('citation')
        verbose_name_plural = _('citations')
        ordering = ['query', 'page_number']

    def __str__(self):
        return f"{self.document_title} (Page {self.page_number})"


class AuditProvenanceRecord(models.Model):
    """
    Tamper-resistant provenance ledger capturing full agent execution history,
    intermediate tool outputs, validation decisions, and token consumption.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )
    request_id = models.CharField(
        _('request ID'),
        max_length=64,
        unique=True,
        db_index=True
    )
    trace_id = models.CharField(
        _('distributed trace ID'),
        max_length=64,
        db_index=True
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='provenance_records'
    )
    user_role = models.CharField(_('user role'), max_length=20, blank=True)
    machine = models.ForeignKey(
        Machine,
        on_delete=models.CASCADE,
        related_name='provenance_records'
    )
    query_record = models.ForeignKey(
        QueryRecord,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='provenance_records'
    )
    user_question = models.TextField(_('user question'))
    query_classification = models.JSONField(_('query classification'), default=dict)
    agent_transitions = models.JSONField(
        _('agent execution steps'),
        default=list,
        help_text=_('Chronological array of agent transitions, tool calls, and latencies.')
    )
    retrieval_operations = models.JSONField(
        _('retrieval metadata'),
        default=dict,
        help_text=_('Candidate chunk count, filters applied, RRF fusion details.')
    )
    retrieved_document_ids = models.JSONField(_('retrieved document IDs'), default=list)
    evidence_chunks = models.JSONField(_('evidence chunks'), default=list)
    evidence_evaluation_outcome = models.CharField(
        _('evidence evaluation outcome'),
        max_length=20,
        choices=EvidenceGateOutcome.choices,
        default=EvidenceGateOutcome.PASS,
        db_index=True
    )
    citation_validation_outcome = models.CharField(
        _('citation validation outcome'),
        max_length=20,
        default='VERIFIED'
    )
    final_answer = models.TextField(_('final answer'), blank=True)
    latencies = models.JSONField(_('node latencies'), default=dict)
    retry_attempts = models.PositiveIntegerField(_('retry attempts'), default=0)
    escalation_status = models.CharField(
        _('escalation status'),
        max_length=20,
        choices=EscalationStatus.choices,
        default=EscalationStatus.NONE
    )
    model_name = models.CharField(_('model identifier'), max_length=100, default='gemini-2.5-flash')
    created_at = models.DateTimeField(_('created at'), auto_now_add=True, db_index=True)

    class Meta:
        db_table = 'assistant_audit_provenance'
        verbose_name = _('audit provenance record')
        verbose_name_plural = _('audit provenance records')
        ordering = ['-created_at']

    def __str__(self):
        return f"Provenance [{self.request_id}] - Trace: {self.trace_id[:8]}"


class Escalation(models.Model):
    """
    Record of inquiries requiring supervisory intervention due to documentation gaps,
    safety hazards, or unresolvable ambiguities.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )
    query = models.ForeignKey(
        QueryRecord,
        on_delete=models.CASCADE,
        related_name='escalations',
        verbose_name=_('query record')
    )
    machine = models.ForeignKey(
        Machine,
        on_delete=models.CASCADE,
        related_name='escalations',
        verbose_name=_('machine')
    )
    engineer = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='filed_escalations',
        verbose_name=_('engineer')
    )
    reason = models.TextField(_('escalation reason'))
    status = models.CharField(
        _('status'),
        max_length=20,
        choices=EscalationStatus.choices,
        default=EscalationStatus.PENDING,
        db_index=True
    )
    resolution_notes = models.TextField(_('supervisor resolution notes'), blank=True)
    resolved_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='resolved_escalations',
        verbose_name=_('resolved by')
    )
    resolved_at = models.DateTimeField(_('resolved at'), null=True, blank=True)
    created_at = models.DateTimeField(_('created at'), auto_now_add=True)

    class Meta:
        db_table = 'assistant_escalations'
        verbose_name = _('escalation')
        verbose_name_plural = _('escalations')
        ordering = ['-created_at']

    def __str__(self):
        return f"Escalation {self.id} for {self.machine.machine_code} [{self.status}]"


class AuditEvent(models.Model):
    """
    Security and administrative audit event logger.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )
    event_type = models.CharField(_('event type'), max_length=50, db_index=True)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='audit_events'
    )
    user_role = models.CharField(_('user role'), max_length=20, blank=True)
    machine = models.ForeignKey(
        Machine,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='audit_events'
    )
    details = models.JSONField(_('event details'), default=dict)
    ip_address = models.GenericIPAddressField(_('IP address'), null=True, blank=True)
    timestamp = models.DateTimeField(_('timestamp'), auto_now_add=True, db_index=True)

    class Meta:
        db_table = 'assistant_audit_events'
        verbose_name = _('audit event')
        verbose_name_plural = _('audit events')
        ordering = ['-timestamp']

    def __str__(self):
        return f"[{self.event_type}] {self.user.email if self.user else 'System'} at {self.timestamp}"
